#!/usr/bin/env node

/**
 * Parses requirement IDs from PRD.md & TRD.md, scans codebase for references,
 * and emits docs/traceability.md (TRD §12.5, NFR-403).
 */

import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';

const args = process.argv.slice(2);
const isStrict = args.includes('--strict');

const root = process.cwd();
const prdPath = existsSync(join(root, 'PRD.md'))
  ? join(root, 'PRD.md')
  : join(root, 'docs', 'PRD.md');
const trdPath = existsSync(join(root, 'TRD.md'))
  ? join(root, 'TRD.md')
  : join(root, 'docs', 'TRD.md');

if (!existsSync(prdPath) || !existsSync(trdPath)) {
  console.error('ERROR: Missing PRD.md or TRD.md.');
  process.exit(1);
}

const ID_PATTERN =
  /(?:PRD |TRD )?\b(FR|NFR|SEC|HR|NG|PRV|CMP|TOOL|MET|RK|OQ|AC)-[A-Z0-9]+(?:-[A-Z0-9]+)*\b/g;

function extractIds(filePath) {
  const content = readFileSync(filePath, 'utf-8');
  const ids = new Set();
  let match = ID_PATTERN.exec(content);
  while (match !== null) {
    const raw = match[0].replace(/^(PRD |TRD )/, '').trim();
    if (raw && !raw.endsWith('-')) {
      ids.add(raw);
    }
    match = ID_PATTERN.exec(content);
  }
  return ids;
}

const allIds = new Set([...extractIds(prdPath), ...extractIds(trdPath)]);

function findScanFiles(dir) {
  const files = [];
  if (!existsSync(dir)) return files;
  const entries = readdirSync(dir, { withFileTypes: true });

  for (const entry of entries) {
    const fullPath = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === 'node_modules' || entry.name === 'dist' || entry.name === '.output') {
        continue;
      }
      files.push(...findScanFiles(fullPath));
    } else if (entry.isFile()) {
      if (/\.(ts|tsx|js|mjs|cjs|json|md)$/.test(entry.name)) {
        files.push(fullPath);
      }
    }
  }
  return files;
}

const scanDirs = [
  join(root, 'packages'),
  join(root, 'apps'),
  join(root, 'tests'),
  join(root, 'scripts'),
];

const targetFiles = [];
for (const dir of scanDirs) {
  targetFiles.push(...findScanFiles(dir));
}

// Map: ID -> { count: number, files: Set<string> }
const idReferences = new Map();
for (const id of allIds) {
  idReferences.set(id, { count: 0, files: new Set() });
}

for (const file of targetFiles) {
  const rel = relative(root, file).replace(/\\/g, '/');
  // Skip generated traceability doc itself
  if (rel === 'docs/traceability.md') continue;

  const content = readFileSync(file, 'utf-8');
  for (const id of allIds) {
    const regex = new RegExp(`\\b${id}\\b`, 'g');
    const matches = content.match(regex);
    if (matches && matches.length > 0) {
      const entry = idReferences.get(id);
      entry.count += matches.length;
      entry.files.add(rel);
    }
  }
}

// Generate docs/traceability.md
const sortedIds = Array.from(allIds).sort();
let markdown = '# Requirements Traceability Matrix (TRD §15, NFR-403)\n\n';
markdown +=
  '> This document is automatically generated by `scripts/check-traceability.mjs`. Do not edit directly.\n\n';
markdown += '| Requirement ID | Status | Count | Referenced in |\n';
markdown += '|---|---|---|---|\n';

let coveredCount = 0;
for (const id of sortedIds) {
  const data = idReferences.get(id);
  const status = data.count > 0 ? 'Covered' : 'Pending';
  if (data.count > 0) coveredCount++;
  const filesList =
    data.files.size > 0
      ? Array.from(data.files)
          .map((f) => `\`${f}\``)
          .join(', ')
      : '—';
  markdown += `| \`${id}\` | ${status} | ${data.count} | ${filesList} |\n`;
}

const totalCount = allIds.size;
const coveragePct = totalCount > 0 ? ((coveredCount / totalCount) * 100).toFixed(1) : '0.0';

markdown += '\n## Summary\n\n';
markdown += `- **Total Requirement IDs:** ${totalCount}\n`;
markdown += `- **Referenced IDs:** ${coveredCount}\n`;
markdown += `- **Unreferenced IDs:** ${totalCount - coveredCount}\n`;
markdown += `- **Coverage:** ${coveragePct}%\n`;

const outPath = join(root, 'docs', 'traceability.md');
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, markdown, 'utf-8');

console.log('Traceability report written to docs/traceability.md');
console.log(`Coverage: ${coveredCount}/${totalCount} IDs referenced (${coveragePct}%)`);

if (isStrict && coveredCount < totalCount) {
  console.error(
    `\nFAILED: Strict traceability check enabled. Missing coverage for ${totalCount - coveredCount} IDs.`,
  );
  process.exit(1);
}

process.exit(0);
